"""Generated Spoken data modules; no quest handlers or second playback queue."""
def lua_string(value):
 if not isinstance(value,str):raise ValueError('Lua text must be a string.')
 escapes={'\\':'\\\\','"':'\\"','\n':'\\n','\r':'\\r','\t':'\\t'}
 return '"'+''.join(escapes.get(c,'\\'+format(ord(c),'03d') if ord(c)<32 or ord(c)==127 else c) for c in value)+'"'

